/**
 * Now 屏的「种子目标」—— 一键可点的三个起点
 *
 * 为什么要有这一层：生成式产品的第一屏是空输入框时，用户得先想清楚"我能用它做什么"。
 * 三个示例把「意图 → 工作区」这件事直接演一遍，比任何一句 slogan 都省事。
 *
 * 🔴 纪律：种子必须**真的能跑通**。示例如果编译失败，就不是示例，是死路。
 *   因此每个 goal 都自带：
 *     · 意图关键词（对齐 `INTENT_PLAYBOOKS` 的 5 类之一）
 *     · 期限（"30 天内" / "两周内"）
 *     · 可数判据（"20 家" / "10 位"）
 *     · 对价（"我们提供…" —— 服务端创建任务要求它非空）
 *   这四项由 `tests/living/now-seeds.test.ts` 逐个断言，改文案时不会悄悄失效。
 *
 * 短标签（`label`）是钩子，goal 才是可编译的句子 —— 两者不共用一份文本：
 * 钩子要短到一眼读完，句子要完整到能被规则解析。
 */

export interface NowSeed {
  /** 稳定 id（用于测试与埋点，不进界面）。 */
  id: string
  /** 界面上的短标签：一行、≤ 20 字、不带句号。 */
  label: string
  /** 点下去填进输入框的完整目标描述（必须能编译通过）。 */
  goal: string
}

