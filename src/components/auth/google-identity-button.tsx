// Load Google Identity Services script
let gisLoaded = false;
let gisLoading = false;

function loadGIS(): Promise<void> {
  if (gisLoaded) return Promise.resolve();
  if (gisLoading) {
    return new Promise((resolve) => {
      const check = setInterval(() => {
        if (gisLoaded) { clearInterval(check); resolve(); }
      }, 100);
    });
  }

  gisLoading = true;
  return new Promise((resolve, reject) => {
    // Check if already loaded
    if ((window as any).google?.accounts) {
      gisLoaded = true;
      gisLoading = false;
      resolve();
      return;
    }

    const script = document.createElement("script");
    script.src = "https://accounts.google.com/gsi/client";
    script.async = true;
    script.defer = true;
    script.onload = () => {
      gisLoaded = true;
      gisLoading = false;
      resolve();
    };
    script.onerror = () => {
      gisLoading = false;
      reject(new Error("Failed to load Google Identity Services"));
    };
    document.head.appendChild(script);
  });
}

// Fetch Google OAuth Client ID from our config API
async function getGoogleClientId(): Promise<string> {
  const res = await fetch("/api/config/firebase");
  const data = await res.json();
  if (!data.valid || !data.config) {
    throw new Error("Firebase config not available");
  }
  // Google Client ID for this Firebase project
  // This is configured in Firebase Console → Authentication → Sign-in method → Google
  // The client ID is auto-generated by Firebase
  return "1054088598785-m8ln40j0ut8k5b2gn1hjbm1r0sbt9oj3.apps.googleusercontent.com";
}

export default function GoogleIdentityButton({
  callbackUrl = "/dashboard",
  label = "Continue with Google",
  disabled = false,
  onError,
}: GoogleIdentityButtonProps) {
  const [isLoading, setIsLoading] = useState(false);

  const handleSignIn = async () => {
    if (isLoading || disabled) return;
    setIsLoading(true);

    let bridgeRes: Response | null = null;
    let bridgeData: any = null;

    try {
      // Step 1: Load Google Identity Services
      await loadGIS();

      // Step 2: Get configuration
      const configRes = await fetch("/api/config/firebase");
      const configData = await configRes.json();
      if (!configData.valid) {
        throw new Error("Firebase config not available");
      }

      // Step 3: Initialize Google Identity Services token client
      const tokenClient = (window as any).google.accounts.oauth2.initTokenClient({
        client_id: "1054088598785-m8ln40j0ut8k5b2gn1hjbm1r0sbt9oj3.apps.googleusercontent.com",
        scope: "email profile",
        callback: async (response: any) => {
          // This callback is called after user selects their Google account
          try {
            if (response.error) {
              console.error("[GIS] Token error:", response);
              if (response.error === "popup_closed_by_user") {
                setIsLoading(false);
                return;
              }
              onError?.(`Google OAuth error: ${response.error}`);
              setIsLoading(false);
              return;
            }

            console.log("[GIS] Got ID token, sending to bridge...");

            // Step 4: Send ID token to our bridge API
            bridgeRes = await fetch("/api/auth/firebase-bridge", {
              method: "POST",
              headers: { "Content-Type": "application/json" },
              body: JSON.stringify({ idToken: response.id_token }),
            });

            bridgeData = await bridgeRes.json();

            if (!bridgeRes.ok || !bridgeData.success) {
              throw new Error(bridgeData.error || "Bridge authentication failed");
            }

            console.log("[GIS] Bridge success, signing in via NextAuth...");

            // Step 5: Sign in via NextAuth
            const csrfRes = await fetch("/api/auth/csrf");
            const { csrfToken } = await csrfRes.json();

            if (!csrfToken) {
              throw new Error("Failed to get CSRF token");
            }

            const loginRes = await signIn("firebase-token", {
              token: bridgeData.signInToken,
              userId: bridgeData.userId,
              callbackUrl,
              csrfToken,
              redirect: false,
            });

            if (loginRes?.ok) {
              window.location.href = callbackUrl;
            } else {
              throw new Error(loginRes?.error || "NextAuth sign-in failed");
            }
          } catch (err: any) {
            console.error("[GIS] Flow error:", err);
            onError?.(err.message || "Google sign-in failed");
            setIsLoading(false);
          }
        },
      });

      // Step 3b: Request token (opens Google popup)
      console.log("[GIS] Requesting Google token...");
      tokenClient.requestAccessToken();
      // Note: the rest of the flow continues in the callback above
      // We do NOT set isLoading(false) here — the callback handles it

    } catch (error: any) {
      console.error("[GoogleIdentityButton] Error:", error);
      onError?.(error.message || "Google sign-in failed");
      setIsLoading(false);
    }
  };

  return (
    <button
      type="button"
      onClick={handleSignIn}
      disabled={isLoading || disabled}
      style={{
        padding: "13px 16px",
        background: colors.bg,
        border: `1px solid ${colors.border}`,
        borderRadius: "12px",
        color: isLoading ? colors.textLoading : colors.text,
        fontSize: "14px",
        fontWeight: "500",
        cursor: isLoading || disabled ? "not-allowed" : "pointer",
        display: "flex",
        alignItems: "center",
        justifyContent: "center",
        gap: "8px",
        opacity: isLoading || disabled ? 0.5 : 1,
        transition: "all 0.2s",
        fontFamily: "'Outfit', sans-serif",
        width: "100%",
      }}
      onMouseEnter={(e) => {
        if (!isLoading && !disabled) e.currentTarget.style.borderColor = colors.borderHover;
      }}
      onMouseLeave={(e) => {
        e.currentTarget.style.borderColor = colors.border;
      }}
    >
      <GoogleIcon />
      {isLoading ? (
        <span style={{ display: "flex", alignItems: "center", gap: "6px" }}>
          <svg className="animate-spin" width="16" height="16" viewBox="0 0 24 24" fill="none">
            <circle cx="12" cy="12" r="10" stroke="currentColor" strokeWidth="3" strokeDasharray="32" strokeLinecap="round"/>
          </svg>
          Signing in...
        </span>
      ) : (
        label
      )}
    </button>
  );
}
