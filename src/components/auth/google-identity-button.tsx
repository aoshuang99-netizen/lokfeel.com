"use client";

/**
 * GoogleIdentityButton — Google OAuth via Google Identity Services (GIS)
 *
 * Completely bypasses Firebase JS SDK. Uses Google's official GIS library:
 * 1. Google popup → returns ID token (JWT)
 * 2. POST ID token to /api/auth/firebase-bridge
 * 3. Bridge verifies via Firebase Admin SDK → returns signInToken
 * 4. NextAuth "firebase-token" provider creates session
 *
 * This eliminates ALL Firebase client SDK issues (bundle, version, config).
 */

import { useState } from "react";
import { signIn } from "next-auth/react";

// DATEASY DARK theme constants
const colors = {
  bg: "rgba(26, 26, 26, 0.9)",
  border: "rgba(85, 85, 85, 0.3)",
  borderHover: "rgba(76, 29, 149, 0.3)",
  text: "#ffffff",
  textLoading: "rgba(255,255,255,0.5)",
};

interface GoogleIdentityButtonProps {
  callbackUrl?: string;
  label?: string;
  disabled?: boolean;
  onError?: (error: string) => void;
}

